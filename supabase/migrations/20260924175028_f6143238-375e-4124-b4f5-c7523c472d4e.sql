CREATE TABLE public.fatias (
  id text PRIMARY KEY,
  epico text NOT NULL,
  nome text NOT NULL,
  peso integer NOT NULL CHECK (peso BETWEEN 1 AND 6),
  entrou_escopo date NOT NULL,
  concluida date,
  marco date NOT NULL,
  removida date,
  situacao text NOT NULL DEFAULT 'nao_iniciada',
  responsavel text
);
GRANT SELECT, UPDATE ON public.fatias TO anon, authenticated;
GRANT ALL ON public.fatias TO service_role;
ALTER TABLE public.fatias ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Leitura pública" ON public.fatias FOR SELECT TO anon, authenticated USING (true);
CREATE POLICY "Atualização pública" ON public.fatias FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);

